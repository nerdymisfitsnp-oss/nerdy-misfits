-- 2. Inky's Custom 3D Print Studio Requests Table
CREATE TABLE IF NOT EXISTS public.custom_print_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  print_type TEXT NOT NULL,
  filament_color TEXT NOT NULL,
  custom_note TEXT,
  estimated_price NUMERIC(10,2),
  customer_email TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Misfit VIP Drop List Subscribers Table
CREATE TABLE IF NOT EXISTS public.vip_subscribers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS) with Public Read for Schedule & Insert for Leads
ALTER TABLE public.market_schedule ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.custom_print_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vip_subscribers ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public read of active schedule"
  ON public.market_schedule FOR SELECT USING (true);

CREATE POLICY "Allow public insert of custom print requests"
  ON public.custom_print_requests FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public insert of VIP subscribers"
  ON public.vip_subscribers FOR INSERT WITH CHECK (true);
